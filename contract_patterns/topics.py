def topic_of(text: str) -> str | None:
    """Определить тему текста по маркерам; None — если тема не распознана."""
    lowered = text.lower()
    # длинные маркеры («неустойк») специфичнее коротких («срок») — взвешиваем по длине
    scores = {
        topic: sum(lowered.count(marker) * len(marker) for marker in markers)
        for topic, markers in TOPICS.items()
    }
    topic, score = max(scores.items(), key=lambda item: item[1])
    return topic if score else None
